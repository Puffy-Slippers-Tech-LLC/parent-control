"""Schema-first diagnostics. Never format an exception or an unknown payload.

Only this module creates diagnostic LogRecords. The catalog is shipped code,
not customer configuration. Field sources must be reviewed with each call site;
types alone cannot determine whether a number represents personal information.
"""

from contextlib import contextmanager
from contextvars import ContextVar
from datetime import datetime
from functools import wraps
import json
