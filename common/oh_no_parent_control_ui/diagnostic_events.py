def record_exception(error):
    source, line = "other", 0
    current = error.__traceback__
    for _ in range(128):
        if current is None:
            break
        module = current.tb_frame.f_globals.get("__name__")
        if type(module) is str and module in FAULT_SOURCES:
            source = FAULT_SOURCES[module]
            line = min(50000, max(0, current.tb_lineno))
        current = current.tb_next
    get_logger("runtime").error("runtime.fault", error_type=error_code(error), source=source, line=line)


def run_cli(callback):
    """Command entrypoints must not dump chained exceptions to the journal."""
    sys.excepthook = lambda _kind, error, _traceback: record_exception(error)
    threading.excepthook = lambda args: record_exception(args.exc_value)
    try:
        return callback()
    except Exception as error:
        record_exception(error)
        return 1
