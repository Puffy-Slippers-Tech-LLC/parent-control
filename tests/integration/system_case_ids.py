def identity_for_case(area, case_id):
    """Return the persistent identity, or None for an unregistered selector."""
    return _BY_SELECTOR.get((area, case_id))


def identity_for_event(nodeid):
    """Map an existing phase::pytest-case event without changing that nodeid."""
    if not isinstance(nodeid, str):
        return None
    phase, separator, case_id = nodeid.partition('::')
    if not phase or not separator:
        return None
    return _BY_CASE.get(case_id)


def validate_inventory(inventories):
    """Refuse executable cases without an explicit checked-in assignment.

    Retired identities may remain reserved in this registry. Callers may validate
    a focused inventory; removal never makes an old numeric ID available again.
    """
    for area, selectors in inventories.items():
        for case_id in selectors:
            identity = identity_for_case(area, case_id)
            if identity is None:
                raise ValueError('system-case-ids:unregistered-case')
            if identity.numeric_id in UNBOUND_CASES:
                raise ValueError('system-case-ids:non-runnable-case')


def parse_recording_ids(value):
    """Resolve explicit persistent IDs without collecting tests or accessing VMs."""
    if not isinstance(value, str) or not value or len(value) > 4096:
        raise ValueError('selection:invalid-numeric-ids')
    parts = value.split(',')
    if any(not part.isascii() or not part.isdecimal() or part.startswith('0') for part in parts):
        raise ValueError('selection:invalid-numeric-ids')
    ids = tuple(int(part) for part in parts)
    if len(ids) != len(set(ids)):
        raise ValueError('selection:duplicate-numeric-id')
    if any(identifier not in BY_ID for identifier in ids):
        raise ValueError('selection:unknown-numeric-id')
    return tuple(BY_ID[identifier] for identifier in ids)
