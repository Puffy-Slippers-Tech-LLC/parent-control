def minute_count(count):
    return ngettext('%(count)d minute', '%(count)d minutes', count) % {'count': count}


def hour_count(count):
    if count != int(count):
        if 0 <= count < 2:
            # French and Brazilian Portuguese use the singular below two;
            # other supported languages retain their decimal form here.
            return pgettext('fractional hours below two', '%(count)g hours') % {'count': count}
        return FRACTIONAL_HOURS % {'count': count}
    return ngettext('%(count)g hour', '%(count)g hours', int(count)) % {'count': count}


def second_count(count):
    return ngettext('%(count)d second', '%(count)d seconds', count) % {'count': count}


def attachments_ready(count):
    return ngettext('%(count)d file attachment ready.', '%(count)d file attachments ready.', count) % {'count': count}


def byte_count(count):
    return ngettext('%(count)d byte', '%(count)d bytes', count) % {'count': count}


