SCHEMA_VERSION = 1
MAX_EVENT_BYTES = 4096
CATALOG = json.loads(Path(__file__).with_name("diagnostic_catalog.json").read_text())
LEVELS = {"DEBUG": 10, "INFO": 20, "WARNING": 30, "ERROR": 40, "CRITICAL": 50}
COMPONENTS = {"broker", "parent", "child", "kiosk"}
_operation = ContextVar("diagnostic_operation", default=0)
_operation_counter = 0
_operation_lock = threading.Lock()


def error_code(error):
    """Return a closed category without calling str/repr on the exception."""
    name = type(error).__name__
    return name if name in ERROR_CODES else "other"


ERROR_CODES = frozenset((
    "other", "Error", "ValueError", "TypeError", "KeyError", "RuntimeError",
    "OSError", "PermissionError", "FileNotFoundError", "TimeoutError",
    "TimeoutExpired", "CalledProcessError", "BackendFailure", "AccessDenied",
    "InvalidRequest", "Busy", "ConfigurationError", "ExecutionPolicyError",
    "RequestException", "ConnectionError", "ConnectTimeout", "ReadTimeout",
    "SSLError", "JSONDecodeError", "CancelledError", "MigrationError",
    "RateLimited", "RollbackFailure", "TimerUsageError", "UninstallCleanupError",
))


def _field(spec, value, *, normalize=False):
    kind = spec["type"]
    if kind == "enum":
        if type(value) is str and value in spec["values"]:
            return value
        if normalize:
            return "other"
    elif kind == "bool":
        if type(value) is bool:
            return value
    elif kind == "int":
        if type(value) is int and spec["min"] <= value <= spec["max"]:
            return value
    elif kind == "number":
        if (type(value) in (int, float) and spec["min"] <= value <= spec["max"]
                and math.isfinite(value)):
            return round(value, 3)
    elif kind == "request":
        # Correlation cookies are random operation references generated by the
        # broker, never account/session/device identifiers or hashes of them.
        if type(value) is str and len(value) == 36:
            try:
                parsed = uuid.UUID(value)
                if parsed.version == 4 and str(parsed) == value:
                    return value
            except ValueError:
                pass
    elif kind == "version":
        if type(value) is str and (value == "unknown" or re.fullmatch(r"[0-9]{1,4}(?:\.[0-9]{1,4}){1,3}", value)):
            return value
    elif kind == "local-timestamp":
        if (type(value) is str and re.fullmatch(
                r"[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}\.[0-9]{3}[+-][0-9]{2}:[0-9]{2}", value)):
            try:
                parsed = datetime.fromisoformat(value)
                if parsed.isoformat(timespec="milliseconds") == value:
                    return value
            except ValueError:
                pass
    raise ValueError("Invalid diagnostic field")


def event(event_id, values=None, *, normalize=False, operation=0):
    if type(event_id) is not str or event_id not in CATALOG:
        raise ValueError("Unknown diagnostic event")
    definition = CATALOG[event_id]
    fields = definition["fields"]
    values = {} if values is None else values
    if type(values) is not dict or values.keys() != fields.keys():
        raise ValueError("Invalid diagnostic fields")
    if type(operation) is not int or not 0 <= operation <= 2**31 - 1:
        raise ValueError("Invalid diagnostic operation")
    return {"v": SCHEMA_VERSION, "event": event_id, "operation": operation,
            "fields": {key: _field(spec, values[key], normalize=normalize)
                       for key, spec in fields.items()}}


def decode(payload, *, component=None):
    if type(payload) is not str or len(payload.encode("utf-8")) > MAX_EVENT_BYTES:
        raise ValueError("Invalid diagnostic envelope")
    try:
        value = json.loads(payload)
    except (ValueError, RecursionError) as error:
        raise ValueError("Invalid diagnostic envelope") from None
    if (type(value) is not dict or set(value) != {"v", "event", "fields", "operation"}
            or type(value["v"]) is not int or value["v"] != SCHEMA_VERSION):
        raise ValueError("Invalid diagnostic envelope")
    safe = event(value["event"], value["fields"], operation=value["operation"])
    if component is not None and component not in CATALOG[safe["event"]]["components"]:
        raise ValueError("Invalid diagnostic source")
    return safe


def encode(value):
    return json.dumps(value, ensure_ascii=True, separators=(",", ":"), sort_keys=True)


def describe(value):
    """Readable support output uses only catalog text and validated fields."""
    definition = CATALOG[value["event"]]
    return f"onpc.{definition['domain']} " + definition["description"].format_map(value["fields"])


@contextmanager
def operation():
    global _operation_counter
    with _operation_lock:
        _operation_counter = _operation_counter % (2**31 - 1) + 1
        number = _operation_counter
    token = _operation.set(number)
    try:
        yield number
    finally:
        _operation.reset(token)


class EventLogger:
    def __init__(self, domain):
        self.domain = domain
        self.name = "onpc." + domain

    def _emit(self, level, event_id, values, named):
        try:
            definition = CATALOG[event_id]
            if definition["domain"] != self.domain:
                raise ValueError("Invalid diagnostic domain")
            if values:
                if named or len(values) != len(definition["fields"]):
                    raise ValueError("Invalid diagnostic fields")
                named = dict(zip(definition["fields"], values))
            safe = event(event_id, named, normalize=True, operation=_operation.get())
        except (KeyError, TypeError, ValueError):
            # Never create a LogRecord containing rejected values, including
            # library exception messages, even when a developer makes a mistake.
            safe = event("diagnostic.rejected")
        logging.getLogger("onpc." + CATALOG[safe["event"]]["domain"]).log(
            LEVELS[level], describe(safe), extra={"onpc_event": True, "onpc_payload": encode(safe)})

    def debug(self, event_id, *values, **named):
        self._emit("DEBUG", event_id, values, named)

    def info(self, event_id, *values, **named):
        self._emit("INFO", event_id, values, named)

    def warning(self, event_id, *values, **named):
        self._emit("WARNING", event_id, values, named)

    def error(self, event_id, *values, **named):
        self._emit("ERROR", event_id, values, named)

    def critical(self, event_id, *values, **named):
        self._emit("CRITICAL", event_id, values, named)


def get_logger(domain):
    if domain not in {entry["domain"] for entry in CATALOG.values()}:
        raise ValueError("Invalid diagnostic domain")
    return EventLogger(domain)


def record_payload(record):
    # Third-party logging is deliberately not copied into diagnostics. Never
    # call getMessage(), format(), handleError(), or inspect traceback locals.
    if (getattr(record, "onpc_event", False) is not True or record.args
            or record.exc_info or record.stack_info):
        return encode(event("diagnostic.unclassified"))
    try:
        return encode(decode(getattr(record, "onpc_payload", None)))
    except (ValueError, TypeError):
        return encode(event("diagnostic.rejected"))


class ConsoleHandler(logging.Handler):
    def emit(self, record):
        try:
            sys.stderr.write(describe(decode(record_payload(record))) + "\n")
        except Exception:
            pass


def configure_console():
    root = logging.getLogger()
    root.handlers.clear()
    root.addHandler(ConsoleHandler())
    root.setLevel(logging.INFO)


def operation_scope(callback):
    @wraps(callback)
    def scoped(*args, **kwargs):
        with operation():
            return callback(*args, **kwargs)
    return scoped


def log_version():
    # Read only the packaged version, never uname/hostnames/environment dumps.
    version = "unknown"
    paths = (Path(__file__).resolve().parents[2] / "data" / "app.json",
             Path("/usr/share/oh-no-parent-control/app.json"))
    for path in paths:
        try:
            candidate = json.loads(path.read_text(encoding="utf-8"))["version"]
            version = _field({"type": "version"}, candidate)
            break
        except (OSError, ValueError, TypeError, KeyError):
            continue
    get_logger("runtime").info("runtime.version", version=version)


